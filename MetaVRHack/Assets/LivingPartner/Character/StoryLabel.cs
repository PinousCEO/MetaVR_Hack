using System.Collections.Generic;
using System.Text;
using UnityEngine;

namespace LivingPartner.Character
{
    /// <summary>The characters the project's own font (Art/Fonts/LPStory-*) has a glyph for.</summary>
    public static class StoryGlyphs
    {
        /// <summary>Everything beyond printable ASCII (32..126) that the font draws.</summary>
        public const string Extra = "·•…–—‘’“”→×°✓";

        public static bool Has(char c) => (c >= ' ' && c <= '~') || c == '\n' || Extra.IndexOf(c) >= 0;

        public static bool CanDraw(string s)
        {
            for (int i = 0; i < s.Length; i++) if (!Has(s[i])) return false;
            return true;
        }
    }

    /// <summary>
    /// One line or block of text in the world. It is drawn with the project's own font ("LPStory", generated by the
    /// editor builder, regular or bold cut). Text that arrives from outside - a window title, the output of a coding
    /// harness - may contain characters that font has no glyph for (Korean, emoji ...); such a text is shown with the
    /// system font instead, so nothing silently disappears.
    /// It also measures: bubbles and line breaks are fitted to the real glyph advances, not to a character count.
    /// Authored by LPSceneBuilder.Label next to a TextMesh; all references are serialized.
    /// </summary>
    public sealed class StoryLabel : MonoBehaviour
    {
        [SerializeField] TextMesh _mesh;
        [SerializeField] MeshRenderer _renderer;
        [SerializeField] Font _story;
        [SerializeField] Font _fallback;
        [SerializeField] bool _bold;

        string _last;
        bool _usingFallback;
        string _wrapSource; float _wrapWidth;

        public TextMesh Mesh => _mesh;
        public bool UsingFallback => _usingFallback;

        public string text
        {
            get => _mesh.text;
            set { _wrapSource = null; Show(value ?? ""); }
        }

        void Show(string s)
        {
            if (s == _last) return;
            _last = s;
            bool fallback = !StoryGlyphs.CanDraw(s);
            if (fallback != _usingFallback)
            {
                _usingFallback = fallback;
                Font f = fallback ? _fallback : _story;
                _mesh.font = f;
                // size and style overrides exist only for the dynamic system font; its 64 px em matches the story font's
                _mesh.fontSize = fallback ? 64 : 0;
                _mesh.fontStyle = fallback && _bold ? FontStyle.Bold : FontStyle.Normal;
                _renderer.sharedMaterial = f.material;
            }
            _mesh.text = s;
        }

        public Color color { get => _mesh.color; set => _mesh.color = value; }
        public TextAnchor anchor { get => _mesh.anchor; set => _mesh.anchor = value; }
        public float characterSize { get => _mesh.characterSize; set => _mesh.characterSize = value; }

        // ------------------------------------------------------------------ measuring
        const float LinePx = 74f;                 // line spacing of the story font (the system font's is within a pixel of it)
        const float FallbackWiden = 1.0f;         // (the other font is measured glyph by glyph, see AdvancePx)
        bool _measuringOther;                     // the text being measured is drawn with the other font (Korean ...)
        static readonly Dictionary<Font, Dictionary<char, float>> Tables = new Dictionary<Font, Dictionary<char, float>>();

        // Sizes are in the PARENT's units (the panel the label sits on), so a panel that is still popping open - its scale
        // animating up from zero - measures and wraps exactly as it will when fully shown.
        float MetresPerPixel => _mesh.characterSize * 0.1f * transform.localScale.x;

        float AdvancePx(char c)
        {
            if (!Tables.TryGetValue(_story, out var table))
            {
                table = new Dictionary<char, float>();
                foreach (var ci in _story.characterInfo) table[(char)ci.index] = ci.advance;
                Tables[_story] = table;
            }
            if (_measuringOther && _fallback != null)
            {
                // the other font is a dynamic one: it says how wide each of its glyphs is at the 64 px em
                if (_fallback.GetCharacterInfo(c, out CharacterInfo ci, 64, _bold ? FontStyle.Bold : FontStyle.Normal)) return ci.advance;
                return c >= 0x1100 ? 54f : 30f;
            }
            if (table.TryGetValue(c, out float a)) return a;
            return c >= 0x1100 ? 64f : 36f;       // no glyph of ours: a full-width CJK cell, or an average Latin letter
        }

        /// <summary>Width in metres of the widest line of s at this label's size.</summary>
        public float Measure(string s)
        {
            if (string.IsNullOrEmpty(s)) return 0f;
            Measuring(s);
            float best = 0f, x = 0f;
            for (int i = 0; i < s.Length; i++)
            {
                if (s[i] == '\n') { best = Mathf.Max(best, x); x = 0f; continue; }
                x += AdvancePx(s[i]);
            }
            return Mathf.Max(best, x) * (StoryGlyphs.CanDraw(s) ? 1f : FallbackWiden) * MetresPerPixel;
        }

        public float Width => Measure(_mesh.text);

        void Measuring(string s)
        {
            _measuringOther = !StoryGlyphs.CanDraw(s);
            if (_measuringOther && _fallback != null && _fallback.dynamic) _fallback.RequestCharactersInTexture(s, 64, _bold ? FontStyle.Bold : FontStyle.Normal);
        }

        public int LineCount
        {
            get
            {
                string s = _mesh.text;
                if (s.Length == 0) return 0;
                int n = 1;
                for (int i = 0; i < s.Length; i++) if (s[i] == '\n') n++;
                return n;
            }
        }

        /// <summary>Line spacing in pixels at the 64 px em: the story font's, or the other font's own when that one is showing.</summary>
        float LineNowPx => _usingFallback && _fallback != null && _fallback.fontSize > 0 ? Mathf.Max(LinePx, _fallback.lineHeight * 64f / _fallback.fontSize) : LinePx;

        public float Height => LineCount * LineNowPx * MetresPerPixel;

        /// <summary>Shows s broken into lines no wider than maxWidth metres (line breaks already in s are kept).</summary>
        public void SetWrapped(string s, float maxWidth)
        {
            s = s ?? "";
            if (s == _wrapSource && Mathf.Approximately(maxWidth, _wrapWidth)) return;
            Measuring(s);
            float k = MetresPerPixel * (StoryGlyphs.CanDraw(s) ? 1f : FallbackWiden);
            float space = AdvancePx(' ') * k;
            var sb = new StringBuilder(s.Length + 8);
            float x = 0f; int wordStart = 0;
            for (int i = 0; i <= s.Length; i++)
            {
                char c = i < s.Length ? s[i] : '\n';
                if (c != ' ' && c != '\n') continue;
                float w = 0f;
                for (int j = wordStart; j < i; j++) w += AdvancePx(s[j]) * k;
                bool lineStart = sb.Length == 0 || sb[sb.Length - 1] == '\n';
                if (!lineStart)
                {
                    if (w > 0f && x + space + w > maxWidth) { sb.Append('\n'); x = 0f; }
                    else { sb.Append(' '); x += space; }
                }
                sb.Append(s, wordStart, i - wordStart); x += w;
                if (c == '\n' && i < s.Length) { sb.Append('\n'); x = 0f; }
                wordStart = i + 1;
            }
            Show(sb.ToString());
            _wrapSource = s; _wrapWidth = maxWidth;
        }
    }
}
